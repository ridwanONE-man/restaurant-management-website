import { MENU_GROUPS, formatSlshAmount, groupOfCategory, waiterStats, type NightEntry } from './data'

function escapeCsv(value: string | number) {
  const text = String(value)
  if (/[",\n]/.test(text)) return `"${text.replace(/"/g, '""')}"`
  return text
}

export function buildNightReport(entry: NightEntry) {
  const lines: string[] = []
  lines.push('CENTRAL FAST FOOD — NIGHT SALES REPORT')
  lines.push(`${entry.date}${entry.timeLabel ? ` · ${entry.timeLabel}` : ''} · ${entry.dayLabel}`)
  lines.push(`Status: ${entry.status}`)
  lines.push('')
  lines.push('=== SUMMARY (SLSH) ===')
  lines.push(`Gross sales: ${formatSlshAmount(entry.totalSales)}`)
  lines.push(`Cash collected: ${formatSlshAmount(entry.cashSales)}`)
  lines.push(`On loan: ${formatSlshAmount(entry.loanAmount)}`)
  lines.push(`Operational expenses: ${formatSlshAmount(entry.expenses)}`)
  lines.push(`Net benefit / final remaining: ${formatSlshAmount(entry.netProfit)}`)
  lines.push(`Items sold: ${entry.covers}`)
  lines.push(`Items on loan: ${entry.loanCovers}`)
  lines.push('')

  if (entry.itemSales?.length) {
    lines.push('=== ITEM SALES ===')
    lines.push('Item, Qty, Unit Price (SLSH), Line Total (SLSH)')
    for (const row of entry.itemSales) {
      lines.push(`${row.itemName}, ${row.qty}, ${row.unitPrice}, ${row.value}`)
    }
    lines.push('')
  }

  if (entry.orders?.length) {
    lines.push('=== BY MENU GROUP ===')
    for (const group of MENU_GROUPS) {
      let qty = 0
      let value = 0
      for (const order of entry.orders) {
        for (const line of order.lines) {
          if (groupOfCategory(line.category) !== group.key) continue
          qty += line.qty
          value += line.qty * line.unitPrice
        }
      }
      lines.push(`${group.title}: ${qty} sold · ${formatSlshAmount(value)}`)
    }
    lines.push('')
  }

  const waiters = waiterStats(entry.orders)
  if (waiters.length) {
    lines.push('=== TEA WAITERS (SHAAH) ===')
    lines.push('Waiter, Shaah cups, Orders, Value (SLSH)')
    for (const w of waiters) {
      lines.push(`${w.name}, ${w.shaahCups}, ${w.orders}, ${w.value}`)
    }
    lines.push('')
  }

  if (entry.orders?.length) {
    lines.push(`=== SALES LOG (${entry.orders.length} orders) ===`)
    for (const order of [...entry.orders].reverse()) {
      const items = order.lines.map((l) => `${l.qty}x ${l.itemName}`).join(' + ')
      lines.push(`${order.time} · ${items} · ${formatSlshAmount(order.total)}${order.waiter ? ` · ${order.waiter}` : ''}`)
    }
    lines.push('')
  }

  const loans = entry.loans ?? []
  lines.push('=== LOANS BY PERSON ===')
  if (!loans.length) {
    lines.push('No loans recorded this night.')
  } else {
    lines.push('Person, Phone, Item, Qty, Unit Price (SLSH), Loan Value (SLSH)')
    for (const loan of loans) {
      lines.push(
        `${loan.personName}, ${loan.phoneNumber || '-'}, ${loan.itemName}, ${loan.qty}, ${loan.unitPrice}, ${loan.value}`,
      )
    }
    lines.push('')
    lines.push('=== LOAN TOTALS BY PERSON ===')
    const byPerson = new Map<string, number>()
    for (const loan of loans) {
      const label = loan.phoneNumber
        ? `${loan.personName} (${loan.phoneNumber})`
        : loan.personName
      byPerson.set(label, (byPerson.get(label) ?? 0) + loan.value)
    }
    for (const [name, total] of byPerson) {
      lines.push(`${name}: ${formatSlshAmount(total)}`)
    }
  }

  const breakdown = entry.expenseBreakdown
  if (breakdown) {
    lines.push('')
    lines.push('=== OPERATIONAL EXPENSES ===')
    if (breakdown.staff.length) {
      lines.push('Staff salaries:')
      for (const person of breakdown.staff) {
        lines.push(`  - ${person.name}: ${formatSlshAmount(person.salary)}`)
      }
      const staffTotal = breakdown.staff.reduce((s, p) => s + p.salary, 0)
      lines.push(`Staff total: ${formatSlshAmount(staffTotal)}`)
    } else {
      lines.push('Staff salaries: 0 SLSH')
    }
    lines.push(`Chicken: ${formatSlshAmount(breakdown.chicken)}`)
    lines.push(`Wholesaler: ${formatSlshAmount(breakdown.wholesaler)}`)
    lines.push(`Grocery spices: ${formatSlshAmount(breakdown.grocerySpices)}`)
    lines.push(`Other: ${formatSlshAmount(breakdown.other)}`)
    lines.push(`Expenses total: ${formatSlshAmount(entry.expenses)}`)
  }

  lines.push('')
  lines.push('Generated by Central Fast Food')
  return lines.join('\n')
}

export function buildNightReportCsv(entry: NightEntry) {
  const rows: (string | number)[][] = []
  rows.push(['Section', 'Field', 'Value'])
  rows.push(['Summary', 'Date', entry.date])
  if (entry.timeLabel) rows.push(['Summary', 'Time', entry.timeLabel])
  rows.push(['Summary', 'Service', entry.dayLabel])
  rows.push(['Summary', 'Status', entry.status])
  rows.push(['Summary', 'Gross sales SLSH', entry.totalSales])
  rows.push(['Summary', 'Cash collected SLSH', entry.cashSales])
  rows.push(['Summary', 'Loan total SLSH', entry.loanAmount])
  rows.push(['Summary', 'Operational expenses SLSH', entry.expenses])
  rows.push(['Summary', 'Net benefit SLSH', entry.netProfit])
  rows.push(['Summary', 'Items sold', entry.covers])
  rows.push(['Summary', 'Items on loan', entry.loanCovers])

  for (const row of entry.itemSales ?? []) {
    rows.push(['Item sale', row.itemName, `qty=${row.qty}; unit=${row.unitPrice}; total=${row.value}`])
  }

  for (const loan of entry.loans ?? []) {
    rows.push([
      'Loan',
      `${loan.personName} / ${loan.phoneNumber || '-'}`,
      `${loan.itemName} x${loan.qty}; unit=${loan.unitPrice}; value=${loan.value}`,
    ])
  }

  const breakdown = entry.expenseBreakdown
  if (breakdown) {
    for (const person of breakdown.staff) {
      rows.push(['Expense staff', person.name, person.salary])
    }
    rows.push(['Expense', 'Chicken', breakdown.chicken])
    rows.push(['Expense', 'Wholesaler', breakdown.wholesaler])
    rows.push(['Expense', 'Grocery spices', breakdown.grocerySpices])
    rows.push(['Expense', 'Other', breakdown.other])
  }

  return rows.map((cols) => cols.map(escapeCsv).join(',')).join('\n')
}

export function downloadTextFile(filename: string, content: string, mime = 'text/plain;charset=utf-8') {
  const blob = new Blob([content], { type: mime })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  a.click()
  URL.revokeObjectURL(url)
}

export function downloadNightReport(entry: NightEntry) {
  const stamp = entry.date.replace(/[,\s]+/g, '-')
  downloadTextFile(`central-fast-food-report-${stamp}.txt`, buildNightReport(entry))
  downloadTextFile(
    `central-fast-food-report-${stamp}.csv`,
    buildNightReportCsv(entry),
    'text/csv;charset=utf-8',
  )
}
